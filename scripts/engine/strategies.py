"""
Modular Swing Trading Strategies for BTC/USDT.
Implements the four independent strategies specified in Section 8:
- Strategy A: Multi-Timeframe Trend Following
- Strategy B: Breakout Trading (Support/Resistance + Volatility Expansion)
- Strategy C: Pullback Trading (EMA Retest + Reversal Confirmation)
- Strategy D: Range-Bound Trading (Sideways Channel, disabled by default)
"""

from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Dict, List, Optional, Tuple, Any
import numpy as np
import pandas as pd

from scripts.engine.regime_detector import MarketRegime


@dataclass
class StrategySignal:
    """Actionable signal generated by an independent strategy module."""
    strategy_name: str
    strategy_type: str
    action: str                           # 'BUY' | 'EXIT' | 'NONE'
    entry_price: float
    suggested_stop_loss: float
    suggested_take_profit: float
    risk_reward_ratio: float
    reasons: List[str] = field(default_factory=list)
    timestamp: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    def to_dict(self) -> Dict[str, Any]:
        return {
            "strategy_name": self.strategy_name,
            "strategy_type": self.strategy_type,
            "action": self.action,
            "entry_price": round(self.entry_price, 2),
            "suggested_stop_loss": round(self.suggested_stop_loss, 2),
            "suggested_take_profit": round(self.suggested_take_profit, 2),
            "risk_reward_ratio": round(self.risk_reward_ratio, 2),
            "reasons": self.reasons,
            "timestamp": self.timestamp
        }


class BaseSwingStrategy(ABC):
    """Abstract base class for all systematic BTC swing strategies."""

    def __init__(self, name: str, strategy_type: str, compatible_regimes: List[MarketRegime], is_enabled: bool = True):
        self.name = name
        self.strategy_type = strategy_type
        self.compatible_regimes = compatible_regimes
        self.is_enabled = is_enabled

    def is_eligible(self, current_regime: MarketRegime) -> bool:
        """Determines if this strategy can operate in the current market regime."""
        return self.is_enabled and current_regime in self.compatible_regimes

    @abstractmethod
    def evaluate_setup(
        self,
        df_1d: pd.DataFrame,
        df_4h: pd.DataFrame,
        df_1h: pd.DataFrame,
        candle_idx: int = -1
    ) -> Optional[StrategySignal]:
        """Evaluates entry and exit opportunities on the current candle."""
        pass


class StrategyA_TrendFollowing(BaseSwingStrategy):
    """
    Strategy A: Multi-Timeframe Trend Following (Priority 1)
    Thesis: Enter 1h swings strictly in the direction of the 4h & Daily macro trend.
    Trigger: Trend confirmed + controlled pullback + momentum recovery + no overextension.
    """

    def __init__(self, is_enabled: bool = True):
        super().__init__(
            name="StrategyA_TrendFollowing",
            strategy_type="Multi-Timeframe Trend",
            compatible_regimes=[MarketRegime.BULLISH_TREND],
            is_enabled=is_enabled
        )

    def evaluate_setup(
        self,
        df_1d: pd.DataFrame,
        df_4h: pd.DataFrame,
        df_1h: pd.DataFrame,
        candle_idx: int = -1
    ) -> Optional[StrategySignal]:
        if df_1h is None or len(df_1h) < 30 or df_4h is None or len(df_4h) < 30:
            return None

        idx_1h = candle_idx if candle_idx >= 0 else len(df_1h) + candle_idx
        idx_4h = candle_idx if candle_idx >= 0 else len(df_4h) + candle_idx

        row_1h = df_1h.iloc[idx_1h]
        row_4h = df_4h.iloc[idx_4h]

        close = float(row_1h.get('close', 0.0))
        ema_20 = float(row_1h.get('ema_20', np.nan))
        ema_50 = float(row_1h.get('ema_50', np.nan))
        rsi = float(row_1h.get('rsi_14', 50.0))
        atr = float(row_1h.get('atr_14', close * 0.015))
        supertrend_4h = int(row_4h.get('supertrend_direction', 0))
        adx_4h = float(row_4h.get('adx_14', 20.0))

        # 1. 4H Trend alignment
        if supertrend_4h != 1 or adx_4h < 20.0:
            return None

        # 2. 1H Pullback condition (close near or above EMA 20, but not overextended)
        if np.isnan(ema_20) or ema_20 <= 0:
            return None

        dist_from_ema = (close - ema_20) / ema_20 * 100.0
        if dist_from_ema > 2.5 or dist_from_ema < -2.0:
            return None

        # 3. 1H Momentum recovery (RSI between 42 and 65)
        if rsi < 42.0 or rsi > 68.0:
            return None

        # 4. Entry confirmation: Close > Open (bullish candle) and MACD histogram expanding
        is_bullish = close > float(row_1h.get('open', close))
        macd_expanding = bool(row_1h.get('macd_hist_expanding', False))

        if is_bullish and (macd_expanding or rsi > 50.0):
            # Calculate dynamic ATR stop-loss and take-profit
            sl = close - (2.0 * atr)
            tp = close + (3.5 * atr)
            rr = (tp - close) / (close - sl) if close > sl else 1.75

            return StrategySignal(
                strategy_name=self.name,
                strategy_type=self.strategy_type,
                action="BUY",
                entry_price=close,
                suggested_stop_loss=sl,
                suggested_take_profit=tp,
                risk_reward_ratio=rr,
                reasons=[
                    f"4H SuperTrend bullish (ADX: {adx_4h:.1f})",
                    f"1H Controlled pullback to EMA 20 ({dist_from_ema:+.2f}%)",
                    f"Momentum recovery confirmed (RSI: {rsi:.1f}, Bullish candle close)"
                ]
            )

        return None


class StrategyB_Breakout(BaseSwingStrategy):
    """
    Strategy B: Breakout Trading
    Thesis: Identify volatility expansion out of consolidation and resistance breaches.
    Trigger: 4H close above resistance + relative volume > 1.2 + not an isolated spike.
    """

    def __init__(self, is_enabled: bool = True):
        super().__init__(
            name="StrategyB_Breakout",
            strategy_type="Resistance Breakout",
            compatible_regimes=[MarketRegime.BULLISH_TREND, MarketRegime.LOW_VOLATILITY, MarketRegime.SIDEWAYS],
            is_enabled=is_enabled
        )

    def evaluate_setup(
        self,
        df_1d: pd.DataFrame,
        df_4h: pd.DataFrame,
        df_1h: pd.DataFrame,
        candle_idx: int = -1
    ) -> Optional[StrategySignal]:
        if df_1h is None or len(df_1h) < 30:
            return None

        idx = candle_idx if candle_idx >= 0 else len(df_1h) + candle_idx
        row = df_1h.iloc[idx]

        close = float(row.get('close', 0.0))
        open_p = float(row.get('open', 0.0))
        resistance = float(row.get('resistance_level', np.nan))
        rel_vol = float(row.get('relative_volume', 1.0))
        atr = float(row.get('atr_14', close * 0.015))
        is_breakout = bool(row.get('is_resistance_breakout', False))

        if np.isnan(resistance) or resistance <= 0:
            return None

        # Check resistance breakout with volume participation
        if is_breakout or (close > resistance and rel_vol >= 1.25 and close > open_p):
            # Dynamic stop just below breakout level or 1.8 ATR
            sl = min(resistance * 0.985, close - (1.8 * atr))
            tp = close + (3.6 * atr)
            rr = (tp - close) / (close - sl) if close > sl else 2.0

            return StrategySignal(
                strategy_name=self.name,
                strategy_type=self.strategy_type,
                action="BUY",
                entry_price=close,
                suggested_stop_loss=sl,
                suggested_take_profit=tp,
                risk_reward_ratio=rr,
                reasons=[
                    f"Resistance breakout at {resistance:.2f}",
                    f"Volume expansion confirms participation ({rel_vol:.2f}x average)",
                    "Strong closed candle above structure"
                ]
            )

        return None


class StrategyC_Pullback(BaseSwingStrategy):
    """
    Strategy C: Pullback Trading
    Thesis: Buy dips in established trends when price stabilizes at moving average support.
    Trigger: Trend bullish + low touches EMA 20/50 + RSI cooling (38-52) + reversal candle (hammer / bounce).
    """

    def __init__(self, is_enabled: bool = True):
        super().__init__(
            name="StrategyC_Pullback",
            strategy_type="Trend Pullback",
            compatible_regimes=[MarketRegime.BULLISH_TREND],
            is_enabled=is_enabled
        )

    def evaluate_setup(
        self,
        df_1d: pd.DataFrame,
        df_4h: pd.DataFrame,
        df_1h: pd.DataFrame,
        candle_idx: int = -1
    ) -> Optional[StrategySignal]:
        if df_1h is None or len(df_1h) < 30:
            return None

        idx = candle_idx if candle_idx >= 0 else len(df_1h) + candle_idx
        row = df_1h.iloc[idx]

        close = float(row.get('close', 0.0))
        low = float(row.get('low', 0.0))
        ema_20 = float(row.get('ema_20', np.nan))
        ema_50 = float(row.get('ema_50', np.nan))
        rsi = float(row.get('rsi_14', 50.0))
        atr = float(row.get('atr_14', close * 0.015))
        is_hammer = bool(row.get('is_bullish_hammer', False))
        is_engulfing = bool(row.get('is_bullish_engulfing', False))
        is_bounce = bool(row.get('is_ema20_pullback_bounce', False) or row.get('is_ema50_pullback_bounce', False))

        if np.isnan(ema_20) or np.isnan(ema_50):
            return None

        # Uptrend requirement
        uptrend = ema_20 > ema_50

        # Retest zone (low within 0.5% of EMA 20 or EMA 50)
        near_ema = (low <= ema_20 * 1.005 and close >= ema_20 * 0.995) or (low <= ema_50 * 1.008 and close >= ema_50 * 0.995)

        # RSI cooling down (not deeply oversold panic, not overbought)
        cooling_rsi = 38.0 <= rsi <= 55.0

        if uptrend and near_ema and cooling_rsi and (is_hammer or is_engulfing or is_bounce or close > float(row.get('open', close))):
            # Technical stop just below the bounce low or EMA 50
            sl = min(low - (0.5 * atr), ema_50 * 0.99)
            tp = close + (3.0 * atr)
            rr = (tp - close) / (close - sl) if close > sl else 2.0

            triggers = []
            if is_hammer: triggers.append("Hammer Pin Bar")
            if is_engulfing: triggers.append("Bullish Engulfing")
            if is_bounce: triggers.append("EMA Bounce")
            if not triggers: triggers.append("Bullish Reversal Candle")

            return StrategySignal(
                strategy_name=self.name,
                strategy_type=self.strategy_type,
                action="BUY",
                entry_price=close,
                suggested_stop_loss=sl,
                suggested_take_profit=tp,
                risk_reward_ratio=rr,
                reasons=[
                    f"Uptrend pullback to EMA support (EMA 20: {ema_20:.2f}, EMA 50: {ema_50:.2f})",
                    f"RSI cooled to constructive level ({rsi:.1f})",
                    f"Reversal structure: {', '.join(triggers)}"
                ]
            )

        return None


class StrategyD_RangeBound(BaseSwingStrategy):
    """
    Strategy D: Range-Bound Trading
    Thesis: Buy near established support in a confirmed sideways channel and exit near resistance.
    NOTE: Disabled initially by default per specification instructions until independently validated.
    """

    def __init__(self, is_enabled: bool = False):
        super().__init__(
            name="StrategyD_RangeBound",
            strategy_type="Range Reversal",
            compatible_regimes=[MarketRegime.SIDEWAYS],
            is_enabled=is_enabled
        )

    def evaluate_setup(
        self,
        df_1d: pd.DataFrame,
        df_4h: pd.DataFrame,
        df_1h: pd.DataFrame,
        candle_idx: int = -1
    ) -> Optional[StrategySignal]:
        if not self.is_enabled or df_1h is None or len(df_1h) < 30:
            return None

        idx = candle_idx if candle_idx >= 0 else len(df_1h) + candle_idx
        row = df_1h.iloc[idx]

        close = float(row.get('close', 0.0))
        low = float(row.get('low', 0.0))
        open_p = float(row.get('open', 0.0))
        support = float(row.get('support_level', np.nan))
        resistance = float(row.get('resistance_level', np.nan))
        rsi = float(row.get('rsi_14', 50.0))

        if np.isnan(support) or np.isnan(resistance) or support >= resistance:
            return None

        # Buy near support (within lower 20% of range)
        range_size = resistance - support
        range_pos = (close - support) / range_size if range_size > 0 else 0.5

        # Avoid middle of the range; buy near bottom (< 0.25) with reversal confirmation
        if range_pos <= 0.25 and close > open_p and rsi < 45.0:
            sl = support * 0.988  # Just below range support
            tp = resistance * 0.98  # Just below range resistance
            rr = (tp - close) / (close - sl) if close > sl else 1.8

            return StrategySignal(
                strategy_name=self.name,
                strategy_type=self.strategy_type,
                action="BUY",
                entry_price=close,
                suggested_stop_loss=sl,
                suggested_take_profit=tp,
                risk_reward_ratio=rr,
                reasons=[
                    f"Range support test at {support:.2f} (Position in range: {range_pos*100:.1f}%)",
                    f"Bullish reversal off range floor (RSI: {rsi:.1f})",
                    f"Targeting resistance at {resistance:.2f}"
                ]
            )

        return None
